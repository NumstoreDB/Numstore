#include "com_numstore_NativeLib.h"

// How numstore reports failure for int / sb_size returns.
// Centralised so it is a one-line change if the convention differs.
#define NS_FAILED(rc) ((rc) < 0)

#define DB(h)   ((nsdb_t *)(intptr_t)(h))
#define TXN(h)  ((txn_t *)(intptr_t)(h))
#define PLAN(h) ((nsdb_plan_t *)(intptr_t)(h))
#define VAR(h)  ((nsdb_var_t *)(intptr_t)(h))
#define PTR(p)  ((jlong)(intptr_t)(p))

//////////////////////////////////// Exceptions

static void
throw_class (JNIEnv *env, const char *cls, const char *msg)
{
  if ((*env)->ExceptionCheck (env)) {
    return; // keep the first exception
  }
  jclass c = (*env)->FindClass (env, cls);
  if (c != NULL) {
    (*env)->ThrowNew (env, c, msg);
    (*env)->DeleteLocalRef (env, c);
  }
}

static void
throw_ns (JNIEnv *env, const char *msg)
{
  throw_class (env, "com/numstore/NumstoreException", msg ? msg : "unknown numstore error");
}

// Throws using the error string of the plan if there is one, else the db.
static void
throw_last (JNIEnv *env, jlong db, jlong plan)
{
  const char *msg = NULL;
  if (plan != 0) {
    msg = ns_plan_strerror (PLAN (plan));
  } else if (db != 0) {
    msg = ns_strerror (DB (db));
  }
  throw_ns (env, msg);
}

//////////////////////////////////// Strings

typedef struct
{
  jbyteArray  arr;
  const char *str;
} cstr_t;

// Returns 0 on success. A NULL array yields str == NULL (used by plan calls).
static int
cstr_get (JNIEnv *env, jbyteArray arr, cstr_t *s)
{
  s->arr = arr;
  s->str = NULL;
  if (arr == NULL) {
    return 0;
  }
  s->str = (const char *)(*env)->GetByteArrayElements (env, arr, NULL);
  return s->str == NULL ? -1 : 0; // OutOfMemoryError already pending
}

static void
cstr_release (JNIEnv *env, cstr_t *s)
{
  if (s->str != NULL) {
    (*env)->ReleaseByteArrayElements (env, s->arr, (jbyte *)s->str, JNI_ABORT);
    s->str = NULL;
  }
}

//////////////////////////////////// Buffers

typedef struct
{
  jbyteArray arr; // non-NULL when ptr is a scratch copy of arr[off, off+len)
  jint       off;
  jint       len;
  void      *ptr;
} nbuf_t;

// Resolves (obj, off, len) to a native pointer. The scratch copy is always
// pre-filled from the array, so bytes numstore does not write keep their
// original values when copied back. Returns 0 on success.
static int
buf_get (JNIEnv *env, jobject obj, jint off, jint len, nbuf_t *b)
{
  memset (b, 0, sizeof *b);
  if (obj == NULL) {
    return 0;
  }

  void *addr = (*env)->GetDirectBufferAddress (env, obj);
  if (addr != NULL) {
    b->ptr = (char *)addr + off;
    b->len = len;
    return 0;
  }

  b->arr = (jbyteArray)obj;
  b->off = off;
  b->len = len;
  b->ptr = malloc (len > 0 ? (size_t)len : 1);
  if (b->ptr == NULL) {
    throw_class (env, "java/lang/OutOfMemoryError", "numstore_jni: scratch buffer");
    return -1;
  }
  if (len > 0) {
    (*env)->GetByteArrayRegion (env, b->arr, off, len, (jbyte *)b->ptr);
  }
  return 0;
}

// Frees the scratch copy, first copying it back into the array if requested.
static void
buf_release (JNIEnv *env, nbuf_t *b, int copy_back)
{
  if (b->arr != NULL) {
    if (copy_back && b->len > 0 && !(*env)->ExceptionCheck (env)) {
      (*env)->SetByteArrayRegion (env, b->arr, b->off, b->len, (const jbyte *)b->ptr);
    }
    free (b->ptr);
  }
  memset (b, 0, sizeof *b);
}

