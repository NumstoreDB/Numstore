/**
 * JNI glue between com.numstore.NativeLib and numstore.h.
 *
 * See NativeLib.java for the calling conventions. In short:
 *  - pointers are jlong (0 == NULL)
 *  - strings are NUL-terminated UTF-8 byte[]; queries are always passed to
 *    numstore as ("%s", query) so '%' is never interpreted
 *  - buffers are (Object buf, jint off, jint len) where buf is a byte[] or a
 *    direct ByteBuffer. Direct buffers are used in place. Arrays go through a
 *    malloc'd scratch copy instead of being pinned, because numstore calls may
 *    block on locks or I/O and GetPrimitiveArrayCritical must not be held
 *    across that.
 *  - failures throw com.numstore.NumstoreException with ns_strerror /
 *    ns_plan_strerror as the message.
 */

#include "numstore.h"

